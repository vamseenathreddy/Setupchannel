def _templated(templates, niche: str) -> list[Story]:
    import datetime
    import random

    from channels.trending.regions import DISTRICTS

    out = [Story(h.format(d=d[0]), "Pulse Boosting", CHANNEL, None, "bank", summary=s)
           for h, s in templates for d in DISTRICTS]
    random.Random(f"{datetime.date.today()}-{niche}").shuffle(out)  # a different order each day
    return out


def bank_stories(niche: str = "innovations") -> list[Story]:
    if niche == "join":
        return _templated(JOIN, niche)
    if niche == "voice":
        return _templated(VOICE, niche)
    facts = JANASENA if niche == "janasena" else FACTS
    return [Story(h, PUBLISHER, link, None, "bank", summary=s) for h, s, link in facts]
